'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const root='src/EvoluFisico.Desktop/wwwroot/';
const read=p=>fs.readFileSync(root+p,'utf8');
const app=read('assets/js/05-app-runtime.js');
const ui=read('assets/js/26-simple-interface.js');
const html=read('index.html');
const sw=read('sw.js');
const native=fs.readFileSync('src/EvoluFisico.Desktop/MainWindow.xaml.cs','utf8');
const sqlite=fs.readFileSync('src/EvoluFisico.Desktop/EncryptedSqliteStore.cs','utf8');
