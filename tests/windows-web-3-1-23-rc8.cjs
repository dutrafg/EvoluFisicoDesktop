const profileStart=app.indexOf("for (const [id, key] of [['avaliador_nome'");
const profileEnd=app.indexOf('window.EFDesktopObjectives?.restore?.(null);',profileStart);
assert(profileStart>=0&&profileEnd>profileStart,'Professional defaults must run after form.reset');
const profileCode=app.slice(profileStart,profileEnd);
const fields=Object.fromEntries(['avaliador_nome','avaliador_registro','avaliador_clinica'].map(k=>[k,{value:''}]));
const bia={open:false};
const prefs={evolufisico_pro_nome:'Profissional QA',evolufisico_pro_cref:'CREF QA',evolufisico_pro_clinica:'Estúdio QA'};
const context={document:{getElementById(id){return id==='ef-method-1'?bia:fields[id]||null;}},localStorage:{getItem(k){return prefs[k]||null;}}};
vm.runInNewContext(profileCode,context);
assert.equal(fields.avaliador_nome.value,'Profissional QA');
assert.equal(fields.avaliador_registro.value,'CREF QA');
assert.equal(fields.avaliador_clinica.value,'Estúdio QA');
assert.equal(bia.open,true,'Bioimpedance should be accessible after reset');
for(const k of Object.keys(fields))fields[k].value='';
for(const k of Object.keys(prefs))delete prefs[k];
vm.runInNewContext(profileCode,{...context});
assert.equal(fields.avaliador_nome.value,'','No configured profile must remain optional');
assert(ui.includes('d.open=true;title.remove()'),'Both measurement groups must open on new assessment');
assert(ui.includes('if(bia)bia.open=true;return r'),'Editing must not close empty bioimpedance');
assert(html.includes('id="bia_pgordura"')&&html.includes('id="avaliador_nome"'));
assert(app.includes('const efHistoryOpenFolders = new Set()'),'Folder state missing');
assert(app.includes('...efHistoryOpenFolders'),'Folder state must survive re-render');
const toggleStart=app.indexOf("pasta.addEventListener('toggle',");
const toggleEnd=app.indexOf('const sumario =',toggleStart);
assert(toggleStart>=0&&toggleEnd>toggleStart,'Folder toggle handler missing');
const opened=new Set();
let handler=null;
const folder={open:true,addEventListener(event,fn){assert.equal(event,'toggle');handler=fn;}};
const state={pasta:folder,termo:'',grupo:{chave:'student-1'},efHistoryOpenFolders:opened};
vm.runInNewContext(app.slice(toggleStart,toggleEnd),state);
handler();assert(opened.has('student-1'),'Opening folder must persist through render');
