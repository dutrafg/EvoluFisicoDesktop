assert(sqlite.includes('ProtectedVault.Encrypt')&&sqlite.includes('BeginTransaction()'),'Encrypted transactional SQLite lost');
assert(vault.includes('AesGcm')&&vault.includes('ProtectedData.Protect'),'Vault encryption lost');
