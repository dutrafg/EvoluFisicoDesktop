'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const prefix='src/EvoluFisico.Desktop/wwwroot/';
const read=p=>fs.readFileSync(prefix+p,'utf8');
const css=read('assets/css/66-web-2028-sync.css');
const legacy=read('assets/css/23-simple-interface.css');
const html=read('index.html'),sw=read('sw.js');
assert.ok(css.includes('#ef-home-analysis .ef-home-compact > .ef-simple-fold-content'),'home analysis scroll selector');
assert.ok(css.includes('#tab-organizacao #eforg-form'),'organization form scroll selector');
assert.ok(css.includes('overscroll-behavior-y: auto;'),'native scroll chaining');
assert.ok(css.includes('-webkit-overflow-scrolling: touch;'),'touch momentum');
assert.ok(css.includes('touch-action: pan-y;'),'touch gesture preserved');
assert.ok(legacy.includes('ef-home-compact>.ef-simple-fold-content{display:block;max-height:500px;overflow:auto}'),'underlying scroll area present');
assert.ok(read('assets/css/51-organization.css').includes('#eforg-form{'),'organization form still present');
assert.ok(html.includes('./assets/css/66-web-2028-sync.css')&&sw.includes('./assets/css/66-web-2028-sync.css'),'offline scroll CSS shipped');
assert.ok(!css.includes('touch-action:none'),'no global touch blocking');
assert.ok(!css.includes('preventDefault'),'no JavaScript touch hijacking');
assert.ok(!html.includes('assets/js/53-custom-cards.js'),'obsolete editor stays unloaded');
console.log('PASS desktop 1.0.11: touch scroll chaining with WebView2 and offline CSS');
